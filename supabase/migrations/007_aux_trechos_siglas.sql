-- Catálogos auxiliares provenientes do seletor Trecho > Sigla em js/campo.js.
-- Preserva os códigos exatamente como estão na interface. Não altera registros existentes.
create table if not exists public.aux_trechos (
  codigo text primary key,
  ordem integer not null default 0,
  ativo boolean not null default true
);
create table if not exists public.aux_siglas (
  trecho_codigo text not null references public.aux_trechos(codigo),
  sigla text not null,
  ordem integer not null default 0,
  ativo boolean not null default true,
  primary key (trecho_codigo, sigla)
);
alter table public.aux_trechos enable row level security;
alter table public.aux_siglas enable row level security;
drop policy if exists aux_trechos_leitura on public.aux_trechos;
create policy aux_trechos_leitura on public.aux_trechos for select to authenticated
using (public.perfil_atual() is not null);
drop policy if exists aux_siglas_leitura on public.aux_siglas;
create policy aux_siglas_leitura on public.aux_siglas for select to authenticated
using (public.perfil_atual() is not null);
drop policy if exists aux_trechos_admin on public.aux_trechos;
create policy aux_trechos_admin on public.aux_trechos for all to authenticated
using (public.perfil_atual()='admin') with check (public.perfil_atual()='admin');
drop policy if exists aux_siglas_admin on public.aux_siglas;
create policy aux_siglas_admin on public.aux_siglas for all to authenticated
using (public.perfil_atual()='admin') with check (public.perfil_atual()='admin');
revoke all on public.aux_trechos,public.aux_siglas from anon,authenticated;
grant select on public.aux_trechos,public.aux_siglas to authenticated;
grant insert,update,delete on public.aux_trechos,public.aux_siglas to authenticated;
